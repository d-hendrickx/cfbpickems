#!/usr/bin/env node
/**
 * tests/extract-suites.mjs — convert the legacy spawned-suite blocks of loadtest.mjs into tests/suites/*.json
 * and turn loadtest.mjs into the CORE suite. Re-runnable: run it again whenever loadtest.mjs has gained blocks
 * (a stale branch merged after the switchover, or the switchover itself on the final tree).
 *
 *   node tests/extract-suites.mjs            report only: what would be created / updated / refused. Exit 1 on any error.
 *   node tests/extract-suites.mjs --write    write manifests + tests/suites/_notes.json, then strip loadtest.mjs
 *   node tests/extract-suites.mjs --write --no-strip    manifests only (loadtest.mjs untouched)
 *
 * Field ownership when a manifest already exists — the extractor owns what the old block said (script, args, label,
 * summary, forbid, post, note, comment, and the floor: the HIGHER of the two wins, the ratchet only tightens); a human
 * owns the rest (tags, isolate, deps, timeoutMs, env, expectedMs) and is never overwritten.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, unlinkSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { extractLegacy, buildCore, suiteIdFor, legacyBlockCount, DEFAULT_TIMEOUT_MS } from './lib/extract.mjs';
import { validateManifest } from './lib/manifest.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const cfbDir = path.resolve(here, '..');

const FIELD_ORDER = ['id', 'kind', 'script', 'args', 'label', 'summary', 'floor', 'forbid', 'post', 'timeoutMs', 'tags', 'isolate', 'deps', 'env', 'expectedMs', 'note'];
const OWNED = ['script', 'args', 'label', 'summary', 'forbid', 'post', 'note'];
const CURATED = ['kind', 'timeoutMs', 'tags', 'isolate', 'deps', 'env', 'expectedMs'];

/**
 * The old blocks carried paragraphs of ratchet history in their floor messages and in the comments above them. The full text is kept
 * VERBATIM in tests/suites/_archive.md (and in git history); a manifest carries only a short description, so a suite stays one small
 * file — and so no manifest can trip munera-ios/scripts/boundarytest.mjs's Tier-1 scan of shipped *.json for iOS-shell mentions.
 */
export function compactNote(text) {
  let t = String(text || '').replace(/\$\{[^}]*\}/g, '').replace(/\\`/g, '`').replace(/\s+/g, ' ').trim();
  t = t.replace(/^[\w./-]+ actually ran [^(]*\(\s*got\s*,?\s*(?:floor \d+\s*[—,-]*\s*)?/i, '').replace(/^\(?got\s*,?\s*floor \d+\s*[—,-]*\s*/i, '').trim();
  if (t.length <= 280) return t;
  const cut = t.slice(0, 280);
  return cut.slice(0, Math.max(cut.lastIndexOf(' '), 200)).replace(/[\s,;:(—-]+$/, '') + ' …';
}

const ARCHIVE_HEAD = '# tests/suites — verbatim legacy notes\n\nGenerated by `node tests/extract-suites.mjs --write`: the comments and floor-message history that sat in loadtest.mjs\nnext to each spawned suite, kept word for word. A manifest carries only a short `note`; this file is where the ratchet history\nlives (git history of loadtest.mjs has the rest). Sections are merged, never dropped, on every re-run.\n';

export function renderArchive(sections) {
  const ids = Object.keys(sections).sort();
  return ARCHIVE_HEAD + ids.map(id => `\n## ${id}\n\n${sections[id].trimEnd()}\n`).join('');
}
export function parseArchive(md) {
  const out = {};
  const parts = md.split(/\n## /).slice(1);
  for (const p of parts) { const nl = p.indexOf('\n'); out[p.slice(0, nl).trim()] = p.slice(nl + 1).trim(); }
  return out;
}

/** The two virtual suites made of loadtest.mjs itself. Created if absent; never overwritten (they are curated). */
function coreManifests() {
  const base = {
    kind: 'core', script: 'loadtest.mjs', args: [], summary: 'strict', floor: 0,
    note: 'loadtest.mjs minus the spawned blocks: every inline section. Its own counts are the contribution (the old harness counted them one by one).',
  };
  return [
    { id: 'core', label: 'core', ...base, env: { CFBP_CORE: 'full' }, tags: ['slow'], expectedMs: 5000 },
    { id: 'core-load', label: 'core-load', ...base, env: { CFBP_CORE: 'load' }, tags: ['quick'], expectedMs: 3000,
      note: 'Section [1] only: every js/ module imports cleanly (RG-03). The --quick tier. `core` includes it, so a tier never runs both.' },
  ];
}

const empty = v => v === undefined || v === '' || (Array.isArray(v) && v.length === 0) || (v && typeof v === 'object' && !Array.isArray(v) && Object.keys(v).length === 0);

/** Stable key order, and no empty arrays / objects / strings — a manifest stays as small as the suite it describes. */
export function orderFields(m) {
  const out = {};
  for (const k of FIELD_ORDER) if (!empty(m[k]) || k === 'floor') out[k] = m[k];
  for (const k of Object.keys(m)) if (!(k in out) && !empty(m[k])) out[k] = m[k];
  return out;
}

function main(argv) {
  const flag = f => argv.includes(f);
  const arg = f => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : null; };
  const write = flag('--write');
  const strip = write && !flag('--no-strip');
  const ltPath = path.resolve(arg('--loadtest') || path.join(cfbDir, 'loadtest.mjs'));
  const suitesDir = path.resolve(arg('--suites-dir') || path.join(here, 'suites'));

  const src = readFileSync(ltPath, 'utf8');
  const { entries, regions, errors, notes } = extractLegacy(src);
  console.log(`loadtest.mjs: ${legacyBlockCount(src)} legacy spawn site(s) → ${entries.length} suite(s), ${regions.length} region(s) to strip`);
  if (errors.length) {
    console.error(`\n❌ ${errors.length} block(s) refused — nothing was written:`);
    for (const e of errors) console.error('  ' + e);
    process.exit(1);
  }

  // ── build manifests ────────────────────────────────────────────────────────────────────────
  const byId = new Map();
  for (const e of entries) {
    const id = suiteIdFor(e.script, e.args, e.env);
    if (byId.has(id)) {
      const prev = byId.get(id);
      if (prev.script !== e.script || JSON.stringify(prev.args) !== JSON.stringify(e.args)) {
        console.error(`❌ two different suites map to the id "${id}": ${prev.script} and ${e.script} — give one a distinct file name`);
        process.exit(1);
      }
      console.error(`❌ ${e.script} is registered twice in loadtest.mjs (labels ${prev.label} and ${e.label}) — the old harness ran it twice; fold into one block first`);
      process.exit(1);
    }
    byId.set(id, { id, ...e });
  }
  // verbatim prose → archive; manifests keep a short note
  const archiveAdd = {};
  for (const [id, e] of byId) {
    const parts = [];
    if (e.label) parts.push(`label: \`${e.label}\` · script: \`${[e.script, ...(e.args || [])].join(' ')}\` · floor at extraction: ${e.floor}`);
    if (e.comment) parts.push('Comment above the block:\n\n' + e.comment.split('\n').map(l => '> ' + l).join('\n'));
    if (e.note) parts.push('Description / floor message:\n\n' + e.note.split('\n').map(l => '> ' + l).join('\n'));
    archiveAdd[id] = parts.join('\n\n');
    e.note = compactNote(e.note);
    delete e.comment;
  }
  for (const [id, text] of Object.entries(notes)) archiveAdd[id] = (archiveAdd[id] ? archiveAdd[id] + '\n\n' : '') + 'Comment above the table loop this suite opens (group comment):\n\n' + text.split('\n').map(l => '> ' + l).join('\n');

  mkdirSync(suitesDir, { recursive: true });
  const plan = [];
  const consider = (id, draft, { curated }) => {
    const file = path.join(suitesDir, `${id}.json`);
    let merged = { ...draft };
    let status = 'new';
    if (existsSync(file)) {
      const old = JSON.parse(readFileSync(file, 'utf8'));
      merged = { ...old };
      for (const k of OWNED) { if (draft[k] !== undefined) merged[k] = draft[k]; else delete merged[k]; }
      merged.floor = Math.max(old.floor ?? 0, draft.floor ?? 0);
      if ((old.floor ?? 0) > (draft.floor ?? 0)) console.log(`  note: ${id} floor in tests/suites (${old.floor}) is ahead of loadtest.mjs (${draft.floor}) — keeping the higher`);
      if (!curated) for (const k of CURATED) if (old[k] !== undefined) merged[k] = old[k];
      // a deadline or a fixed zone the old block SAYS is never dropped because the manifest predates it: a human value wins, an absent one is filled
      for (const k of ['timeoutMs', 'env']) if (old[k] === undefined && draft[k] !== undefined) merged[k] = draft[k];
      status = JSON.stringify(orderFields(old)) === JSON.stringify(orderFields({ ...merged, id })) ? 'unchanged' : 'updated';
    }
    plan.push({ id, file, manifest: orderFields({ ...merged, id }), status });
  };
  for (const [id, d] of byId) consider(id, d, { curated: false });
  for (const c of coreManifests()) {
    const file = path.join(suitesDir, `${c.id}.json`);
    if (existsSync(file)) { plan.push({ id: c.id, file, manifest: JSON.parse(readFileSync(file, 'utf8')), status: 'unchanged' }); continue; }
    plan.push({ id: c.id, file, manifest: orderFields(c), status: 'new' });
  }

  // validate everything we are about to write
  const bad = [];
  for (const p of plan) for (const err of validateManifest(p.manifest, `${p.id}.json`, { cfbDir })) bad.push(err);
  if (bad.length) { console.error('\n❌ generated manifests do not validate — nothing was written:'); for (const b of bad) console.error('  ' + b); process.exit(1); }

  const counts = plan.reduce((a, p) => { a[p.status] = (a[p.status] || 0) + 1; return a; }, {});
  console.log(`manifests: ${JSON.stringify(counts)}`);

  // suites that exist on disk as manifests but whose block is gone from loadtest.mjs are normal after the switchover; list orphans only
  const known = new Set(plan.map(p => p.id));
  const existing = existsSync(suitesDir) ? readdirSync(suitesDir).filter(f => f.endsWith('.json') && !f.startsWith('_')).map(f => f.replace(/\.json$/, '')) : [];
  const extra = existing.filter(i => !known.has(i));
  if (extra.length) console.log(`manifests not produced by loadtest.mjs (hand-added or post-switchover): ${extra.length}`);

  if (!write) { console.log('\n(report only — pass --write to create the manifests and strip loadtest.mjs)'); return; }

  for (const p of plan) if (p.status !== 'unchanged') writeFileSync(p.file, JSON.stringify(p.manifest, null, 2) + '\n');
  // verbatim prose, merged with whatever earlier runs archived
  const archiveFile = path.join(suitesDir, '_archive.md');
  const archived = existsSync(archiveFile) ? parseArchive(readFileSync(archiveFile, 'utf8')) : {};
  writeFileSync(archiveFile, renderArchive({ ...archived, ...archiveAdd }));
  console.log(`wrote ${plan.filter(p => p.status !== 'unchanged').length} manifest(s) to ${path.relative(process.cwd(), suitesDir) || '.'}`);

  if (strip) {
    const core = buildCore(src, regions);
    const check = extractLegacy(core);
    if (check.entries.length || check.errors.length) { console.error('❌ internal error: stripped source still contains legacy blocks — loadtest.mjs left untouched'); process.exit(1); }
    const tmp = path.join(tmpdir(), `loadtest-core-check-${process.pid}.mjs`);   // outside the checkout: never a scratch file in the tree
    writeFileSync(tmp, core);
    const r = spawnSync(process.execPath, ['--check', tmp], { encoding: 'utf8' });
    try { unlinkSync(tmp); } catch { /* best effort */ }
    if (r.status !== 0) { console.error(`❌ stripped loadtest.mjs does not parse — left untouched:\n${r.stderr}`); process.exit(1); }
    writeFileSync(ltPath, core);
    console.log(`loadtest.mjs → core suite (${src.split('\n').length} → ${core.split('\n').length} lines, ${regions.length} block(s) moved to manifests)`);
  }
}

const isEntry = (() => { try { return !!process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url)); } catch { return false; } })();
if (isEntry) main(process.argv.slice(2));
